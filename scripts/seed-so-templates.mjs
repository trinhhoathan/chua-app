/**
 * Seed metadata lòng sớ + (tuỳ chọn) upload gzip lên Supabase Storage.
 *
 * Usage:
 *   node scripts/seed-so-templates.mjs              # chỉ ghi SQL + index local
 *   node scripts/seed-so-templates.mjs --upload     # cần SUPABASE_SERVICE_ROLE_KEY
 *   node scripts/seed-so-templates.mjs --sql-only   # chỉ xuất SQL upsert
 */
import fs from 'node:fs';
import path from 'node:path';
import zlib from 'node:zlib';
import { fileURLToPath } from 'node:url';
import { createClient } from '@supabase/supabase-js';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const DATA = path.join(ROOT, 'so-data');
const OUT_SQL = path.join(ROOT, 'so-data', 'seed-meta.sql');
const OUT_INDEX = path.join(ROOT, 'src', 'data', 'so-templates-index.json');

const args = new Set(process.argv.slice(2));
const doUpload = args.has('--upload');

function esc(s) {
  return String(s ?? '')
    .replace(/\\/g, '\\\\')
    .replace(/'/g, "''");
}

function loadEnvLocal() {
  const p = path.join(ROOT, '.env.local');
  if (!fs.existsSync(p)) return;
  for (const line of fs.readFileSync(p, 'utf8').split(/\r?\n/)) {
    const m = line.match(/^([A-Z0-9_]+)=(.*)$/);
    if (!m) continue;
    if (!process.env[m[1]]) process.env[m[1]] = m[2].trim();
  }
}

loadEnvLocal();

const longsoDir = path.join(DATA, 'longsos');
const bosoDir = path.join(DATA, 'bosos');
const luatDir = path.join(DATA, 'liemluatsos');

if (!fs.existsSync(longsoDir)) {
  console.error('Missing so-data/longsos — copy data first.');
  process.exit(1);
}

const templates = [];
const files = fs.readdirSync(longsoDir).filter((f) => f.endsWith('.json'));
console.log(`Reading ${files.length} longsos...`);

for (const f of files) {
  const id = Number(f.replace(/\.json$/, ''));
  const j = JSON.parse(fs.readFileSync(path.join(longsoDir, f), 'utf8'));
  let config = {};
  const luatPath = path.join(luatDir, f);
  // liemluat files use different ids sometimes — match by longso field
  if (fs.existsSync(luatPath)) {
    try {
      config = JSON.parse(fs.readFileSync(luatPath, 'utf8')).config ?? {};
    } catch {
      /* ignore */
    }
  }
  const sizes = Object.keys(j.template || {});
  templates.push({
    longso_id: id,
    name: j.name || `Sớ ${id}`,
    lang: j.lang || 'qn',
    kind: j.kind || 'tradition',
    placeholders: j.placeholders || [],
    paper_sizes: sizes,
    storage_path: `longsos/${id}.json.gz`,
    config,
    active: j.active !== false,
  });
}

// Map liemluat by longso number when filename differs
const luatByLongso = new Map();
if (fs.existsSync(luatDir)) {
  for (const f of fs.readdirSync(luatDir).filter((x) => x.endsWith('.json'))) {
    try {
      const j = JSON.parse(fs.readFileSync(path.join(luatDir, f), 'utf8'));
      if (typeof j.longso === 'number') luatByLongso.set(j.longso, j.config ?? {});
    } catch {
      /* ignore */
    }
  }
}
for (const t of templates) {
  if (luatByLongso.has(t.longso_id)) t.config = luatByLongso.get(t.longso_id);
}

const sets = [];
if (fs.existsSync(bosoDir)) {
  for (const f of fs.readdirSync(bosoDir).filter((x) => x.endsWith('.json'))) {
    const j = JSON.parse(fs.readFileSync(path.join(bosoDir, f), 'utf8'));
    const id = f.replace(/\.json$/, '');
    sets.push({
      id,
      name: j.name || id,
      longso_ids: j.cacLongSo || [],
      active: j.active !== false,
      sort_order: 0,
    });
  }
  sets.sort((a, b) => a.name.localeCompare(b.name, 'vi'));
  sets.forEach((s, i) => {
    s.sort_order = i;
  });
}

fs.mkdirSync(path.dirname(OUT_INDEX), { recursive: true });
fs.writeFileSync(
  OUT_INDEX,
  JSON.stringify(
    {
      templates: templates.map((t) => ({
        id: t.longso_id,
        name: t.name,
        lang: t.lang,
        kind: t.kind,
        placeholders: t.placeholders,
        sizes: t.paper_sizes,
      })),
      sets: sets.map((s) => ({
        id: s.id,
        name: s.name,
        longsoIds: s.longso_ids,
      })),
    },
    null,
    0,
  ),
);
console.log('Wrote', OUT_INDEX);

const sqlParts = [];
sqlParts.push('-- Auto-generated by scripts/seed-so-templates.mjs');
sqlParts.push('begin;');
for (const t of templates) {
  sqlParts.push(
    `insert into public.so_templates (longso_id, name, lang, kind, placeholders, paper_sizes, storage_path, config, active, updated_at)
values (${t.longso_id}, '${esc(t.name)}', '${esc(t.lang)}', '${esc(t.kind)}', '${esc(JSON.stringify(t.placeholders))}'::jsonb, array[${t.paper_sizes.map((s) => `'${esc(s)}'`).join(',')}]::text[], '${esc(t.storage_path)}', '${esc(JSON.stringify(t.config))}'::jsonb, ${t.active}, now())
on conflict (longso_id) do update set
  name = excluded.name,
  lang = excluded.lang,
  kind = excluded.kind,
  placeholders = excluded.placeholders,
  paper_sizes = excluded.paper_sizes,
  storage_path = excluded.storage_path,
  config = excluded.config,
  active = excluded.active,
  updated_at = now();`,
  );
}
for (const s of sets) {
  sqlParts.push(
    `insert into public.so_template_sets (id, name, longso_ids, active, sort_order, updated_at)
values ('${esc(s.id)}', '${esc(s.name)}', array[${s.longso_ids.join(',')}]::integer[], ${s.active}, ${s.sort_order}, now())
on conflict (id) do update set
  name = excluded.name,
  longso_ids = excluded.longso_ids,
  active = excluded.active,
  sort_order = excluded.sort_order,
  updated_at = now();`,
  );
}
sqlParts.push('commit;');
fs.writeFileSync(OUT_SQL, sqlParts.join('\n'));
console.log('Wrote', OUT_SQL, `(${templates.length} templates, ${sets.length} sets)`);

if (!doUpload) {
  console.log('Skip Storage upload (pass --upload + SUPABASE_SERVICE_ROLE_KEY to upload gzip).');
  process.exit(0);
}

const url = process.env.NEXT_PUBLIC_SUPABASE_URL;
const key = process.env.SUPABASE_SERVICE_ROLE_KEY;
if (!url || !key) {
  console.error('Missing NEXT_PUBLIC_SUPABASE_URL or SUPABASE_SERVICE_ROLE_KEY');
  process.exit(1);
}

const supabase = createClient(url, key, {
  auth: { persistSession: false, autoRefreshToken: false },
});

let ok = 0;
let fail = 0;
for (const t of templates) {
  const raw = fs.readFileSync(path.join(longsoDir, `${t.longso_id}.json`));
  const gz = zlib.gzipSync(raw, { level: 9 });
  const { error } = await supabase.storage
    .from('so-templates')
    .upload(t.storage_path, gz, {
      contentType: 'application/gzip',
      upsert: true,
    });
  if (error) {
    fail++;
    console.error('Upload fail', t.longso_id, error.message);
  } else {
    ok++;
    if (ok % 50 === 0) console.log(`Uploaded ${ok}/${templates.length}`);
  }
}
console.log(`Upload done: ${ok} ok, ${fail} fail`);
